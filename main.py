# Load Data
"""

import pandas as pd

df = pd.read_csv('/depression.csv')
df

# Let's inspect the unique values for our key categorical columns
print("Unique Genders:")
print(df['Gender'].unique())

print("\nUnique Professions:")
print(df['Profession'].unique())

print("\nUnique Dietary Habits:")
print(df['Dietary Habits'].unique())

"""# **Data preparation**

## Data separation as X and Y
"""

y = df['Depression']
y

df_clean = df.dropna()

# Re-assign target y from cleaned data
y = df_clean['Depression']

# Drop target column and unique identifier 'id' from cleaned data
x = df_clean.drop(columns=['Depression', 'id'])

# One-hot encode categorical features
x = pd.get_dummies(x, drop_first=True)

x

"""## Data splitting"""

from sklearn.model_selection import train_test_split

# Re-split the processed, fully-numerical data
x_train, x_test, y_train, y_test = train_test_split(x, y, test_size=0.2, random_state=100)

x_test

"""# **Model Building**

## Linear Regression

### **Training the model**
"""

from sklearn.linear_model import LinearRegression

# Fill any leftover missing NaN values with 0 to prevent the ValueError
x_train = x_train.fillna(0)
x_test = x_test.fillna(0)

# Initialize and fit the model
lr = LinearRegression()
lr.fit(x_train, y_train)
print("Model trained successfully!")

"""**Aplying the model to make a prediction**"""

y_lr_train_pred = lr.predict(x_train)
y_lr_test_pred = lr.predict(x_test)

y_lr_train_pred

y_lr_test_pred

"""**Evaluate model performance**"""

from sklearn.metrics import mean_squared_error, r2_score

lr_train_mse = mean_squared_error(y_train, y_lr_train_pred)
lr_train_r2 = r2_score(y_train, y_lr_train_pred)

lr_test_mse = mean_squared_error(y_test, y_lr_test_pred)
lr_test_r2 = r2_score(y_test, y_lr_test_pred)

print('LR MSE (Train): ',lr_train_mse)
print('LR R2 (Train): ',lr_train_r2)

print('LR MSE (Test): ',lr_test_mse)
print('LR R2 (Test): ',lr_test_r2)

lr_results = pd.DataFrame(['Linear regression', lr_train_mse, lr_train_r2, lr_test_mse, lr_test_r2]).transpose()
lr_results.columns = ['Method', 'Training MSE', 'Training R2', 'Test MSE', 'Test R2']

lr_results

"""## **Random forest**

### **Training the model**
"""

from sklearn.ensemble import RandomForestRegressor

rf = RandomForestRegressor(max_depth=2, random_state=100)
rf.fit(x_train, y_train)

"""### **Applying the model to make a prediction**"""

y_rf_train_pred = rf.predict(x_train)
y_rf_test_pred = rf.predict(x_test)

"""### **Evaluate model performance**"""

from sklearn.metrics import mean_squared_error, r2_score

rf_train_mse = mean_squared_error(y_train, y_rf_train_pred)
rf_train_r2 = r2_score(y_train, y_rf_train_pred)

rf_test_mse = mean_squared_error(y_test, y_rf_test_pred)
rf_test_r2 = r2_score(y_test, y_rf_test_pred)

rf_results = pd.DataFrame(['Random forest', rf_train_mse, rf_train_r2, rf_test_mse, rf_test_r2]).transpose()
rf_results.columns = ['Method', 'Training MSE', 'Training R2', 'Test MSE', 'Test R2']
rf_results

"""## **Model comparison**"""

df_models = pd.concat([lr_results, rf_results], axis=0)
df_models.reset_index(drop=True)

